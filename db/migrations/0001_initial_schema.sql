-- =============================================================================
-- Suncly - initial database schema
-- Migration: 0001_initial_schema.sql
-- Target:    Cloudflare D1 (SQLite)
--
-- What Suncly does: it fetches an A2A agent's Agent Card, tests whether the
-- agent really does what the card claims, and issues a signed attestation.
--
-- Reading order (same as the data flow):
--   1. organizations, users, organization_members, api_keys   -> who uses Suncly
--   2. agents, card_snapshots                                 -> what is tested
--   3. check_definitions                                      -> which tests exist
--   4. runs, check_results, http_exchanges                    -> what happened
--   5. signing_keys, attestations                             -> the signed result
--   6. audit_log                                              -> who did what
--
-- Conventions (SQLite has fewer types than Postgres, so these matter):
--   * IDs are UUID strings generated by the application (crypto.randomUUID()).
--     Exceptions: check_definitions (readable text id), audit_log (integer).
--   * Timestamps are TEXT in ISO 8601 UTC, e.g. 2026-10-03T18:50:54.615Z.
--     created_at fills itself in; updated_at must be set by the application.
--   * Booleans are INTEGER 0 or 1.
--   * JSON is stored as TEXT and validated with json_valid().
--   * Fixed value lists (status, role, outcome ...) are enforced with CHECK.
--   * Test data (snapshots, results, exchanges, attestations) is append-only:
--     rows are inserted, never edited. A new test = a new run.
--   * No BEGIN/COMMIT here: D1 applies each migration file atomically itself.
-- =============================================================================

-- =============================================================================
-- 1. WHO USES SUNCLY
-- =============================================================================

-- A customer team. Every agent and run belongs to exactly one organization.
CREATE TABLE organizations (
    id          TEXT PRIMARY KEY CHECK (length(id) = 36),
    name        TEXT NOT NULL CHECK (length(trim(name)) > 0),
    -- URL-safe unique name: lowercase letters, digits and hyphens (e.g. "acme-ai").
    slug        TEXT NOT NULL UNIQUE
                CHECK (length(slug) > 0
                   AND slug NOT GLOB '*[^a-z0-9-]*'
                   AND slug NOT GLOB '-*'
                   AND slug NOT GLOB '*-'
                   AND slug NOT GLOB '*--*'),
    created_at  TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
    updated_at  TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
) STRICT;

-- A person who can log in. Passwords/sessions are handled by the auth
-- provider, not stored here.
CREATE TABLE users (
    id            TEXT PRIMARY KEY CHECK (length(id) = 36),
    email         TEXT NOT NULL CHECK (email LIKE '%_@_%'),
    display_name  TEXT,
    created_at    TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
    updated_at    TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
) STRICT;

-- Email is unique regardless of letter case.
CREATE UNIQUE INDEX users_email_lower_key ON users (lower(email));

-- Which user belongs to which organization, and with what role.
CREATE TABLE organization_members (
    organization_id  TEXT NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
    user_id          TEXT NOT NULL REFERENCES users (id)         ON DELETE CASCADE,
    role             TEXT NOT NULL DEFAULT 'member'
                     CHECK (role IN ('owner', 'admin', 'member')),
    created_at       TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
    PRIMARY KEY (organization_id, user_id)
) STRICT;

CREATE INDEX organization_members_user_id_idx ON organization_members (user_id);

-- Keys for calling the Suncly API from CI or scripts.
CREATE TABLE api_keys (
    id               TEXT PRIMARY KEY CHECK (length(id) = 36),
    organization_id  TEXT NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
    name             TEXT NOT NULL CHECK (length(trim(name)) > 0),
    -- First characters of the key, shown in the UI so the user can recognise it.
    key_prefix       TEXT NOT NULL CHECK (length(key_prefix) BETWEEN 4 AND 16),
    -- SHA-256 (lowercase hex) of the full key. The key itself is NEVER stored.
    key_hash         TEXT NOT NULL UNIQUE
                     CHECK (length(key_hash) = 64 AND key_hash NOT GLOB '*[^0-9a-f]*'),
    created_by       TEXT REFERENCES users (id) ON DELETE SET NULL,
    created_at       TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
    last_used_at     TEXT,
    revoked_at       TEXT
) STRICT;

CREATE INDEX api_keys_organization_id_idx ON api_keys (organization_id);

-- =============================================================================
-- 2. WHAT IS TESTED
-- =============================================================================

-- An A2A agent registered for testing. One row per agent per organization.
CREATE TABLE agents (
    id               TEXT PRIMARY KEY CHECK (length(id) = 36),
    organization_id  TEXT NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
    name             TEXT NOT NULL CHECK (length(trim(name)) > 0),
    -- Full https URL of the Agent Card. Only https is allowed
    -- (SSRF protection starts here).
    card_url         TEXT NOT NULL CHECK (substr(card_url, 1, 8) = 'https://' AND length(card_url) > 8),
    created_by       TEXT REFERENCES users (id) ON DELETE SET NULL,
    created_at       TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
    updated_at       TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
    UNIQUE (organization_id, card_url)
) STRICT;

-- An exact copy of an Agent Card at the moment it was fetched. Immutable.
-- A changed card = a new snapshot.
CREATE TABLE card_snapshots (
    id                 TEXT PRIMARY KEY CHECK (length(id) = 36),
    agent_id           TEXT NOT NULL REFERENCES agents (id) ON DELETE CASCADE,
    -- The Agent Card JSON exactly as the agent served it.
    raw_card           TEXT NOT NULL CHECK (json_valid(raw_card)),
    -- SHA-256 (lowercase hex) of the raw response bytes.
    -- This hash goes into the attestation.
    sha256             TEXT NOT NULL
                       CHECK (length(sha256) = 64 AND sha256 NOT GLOB '*[^0-9a-f]*'),
    -- A2A protocol version the card declares, if any.
    protocol_version   TEXT,
    -- 1 = the card passed JSON Schema validation for the A2A spec, 0 = it did not.
    is_schema_valid    INTEGER NOT NULL CHECK (is_schema_valid IN (0, 1)),
    -- JSON array of schema validation errors; empty array when valid.
    validation_errors  TEXT NOT NULL DEFAULT '[]'
                       CHECK (json_valid(validation_errors) AND json_type(validation_errors) = 'array'),
    fetched_at         TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
    UNIQUE (agent_id, sha256),
    -- Lets runs reference (id, agent_id) so a run cannot point at another agent's card.
    UNIQUE (id, agent_id),
    -- A valid card has no validation errors.
    CHECK (is_schema_valid = 0 OR json_array_length(validation_errors) = 0)
) STRICT;

