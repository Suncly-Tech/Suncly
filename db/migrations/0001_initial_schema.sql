-- Catalog of all checks the test engine can run.
-- Rows are added by migrations, not by users.
CREATE TABLE check_definitions (
    -- Stable human-readable id, e.g. "capability.streaming".
    -- Never renamed once released.
    id           TEXT PRIMARY KEY
                 CHECK (id GLOB '[a-z]*.[a-z]*' AND id NOT GLOB '*[^a-z_.]*' AND id NOT GLOB '*..*' AND id NOT GLOB '*.'),
    category     TEXT NOT NULL
                 CHECK (category IN ('card', 'transport', 'capability', 'skill', 'error_handling', 'auth')),
    severity     TEXT NOT NULL CHECK (severity IN ('critical', 'major', 'minor')),
    title        TEXT NOT NULL,
    description  TEXT NOT NULL,
    -- 1 = the check runs once for every skill on the card; 0 = once per run.
    per_skill    INTEGER NOT NULL DEFAULT 0 CHECK (per_skill IN (0, 1)),
    is_active    INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
    created_at   TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
) STRICT;

